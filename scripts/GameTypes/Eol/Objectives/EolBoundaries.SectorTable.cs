        /// <summary>The frozen sector of every play-map tile (w x h), or null when the table doesn't fit this level.</summary>
        static byte[] FixedSectorMap(int w, int h)
        {
            if (w != FixedSectorWidth || h < FixedSectorRows.Length)
                return null;
            byte[] map = new byte[w * h];
            for (int y = 0; y < FixedSectorRows.Length; y++)
            {
                int x = 0;
                foreach (string run in FixedSectorRows[y].Split(' '))
                {
                    byte s = (byte)(run[0] - '0');
                    int n = int.Parse(run.Substring(1));
                    for (int k = 0; k < n && x < w; k++, x++)
                        map[y * w + x] = s;
                }
                if (x != w)
                    return null;
            }
            for (int y = FixedSectorRows.Length; y < h; y++)   // (rows below the table: the row above)
                Array.Copy(map, (y - 1) * w, map, y * w, w);
            return map;
        }

